#!/usr/bin/env python3
"""Generates SbxTerminal/src/fonts.h from public-domain X11 misc-fixed BDF fonts.

usage: gen_font.py OUTPUT.h 7x13.bdf 9x15.bdf 10x20.bdf

Box drawing, blocks and braille are drawn by render.cpp, so they aren't included. Symbols agents
use that a font lacks are drawn here at 7x13 and scaled to fit.
"""
import re
import sys

