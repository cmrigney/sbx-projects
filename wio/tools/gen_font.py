ALIASES = {
    0x23FA: 0x25CF,  # Claude Code's tool-call dot
    0x2714: 0x2713,
    0x2718: 0x2717,
    0x273D: 0x273B,
    0x2736: 0x273B,
    0x2733: 0x273B,
}


def parse(path):
    glyphs = {}
    text = open(path, errors="ignore").read()
    for block in re.findall(r"STARTCHAR.*?ENDCHAR", text, re.S):
        code = int(re.search(r"^ENCODING (-?\d+)", block, re.M).group(1))
        bw, bh, bx, by = map(int, re.search(r"^BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", block, re.M).groups())
        rows = re.search(r"BITMAP\n(.*?)ENDCHAR", block, re.S).group(1).split()
        out = [0] * H
        top = H - DESCENT - by - bh
        for i, row in enumerate(rows):
            y = top + i
            if not 0 <= y < H:
                continue
            bits = int(row, 16) << (8 * (len(row) // 2 + (len(row) % 2)) - len(row) * 4)
            value = bits >> max(0, len(row) * 4 - 8) if len(row) > 2 else bits
            out[y] = (value >> bx if bx >= 0 else value << -bx) & 0xFE
        glyphs[code] = out
    return glyphs


def art(s):
    rows = s.strip("\n").split("\n")
    assert len(rows) == H and all(len(r) == W for r in rows)
    return [sum(0x80 >> i for i, c in enumerate(r) if c == "#") for r in rows]


def main():
    font = parse(sys.argv[1])
    chosen = {c: g for c, g in font.items() if any(a <= c <= b for a, b in RANGES)}
    for code, drawing in CUSTOM.items():
        chosen[code] = art(drawing)
    for code, target in ALIASES.items():
        chosen[code] = chosen[target]
    codes = sorted(chosen)
    with open(sys.argv[2], "w") as f:
        f.write("// 7x13 from X11 misc-fixed (public domain). Generated by wio/tools/gen_font.py.\n")
        f.write("// Each glyph is 13 rows, with the leftmost pixel in the top bit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"static const int kFontGlyphs = {len(codes)};\n")
        f.write("static const uint16_t kFontCodes[] = {\n")
        for i in range(0, len(codes), 14):
            f.write("  " + ",".join(f"0x{c:04X}" for c in codes[i:i + 14]) + ",\n")
        f.write("};\nstatic const uint8_t kFontBitmaps[][13] = {\n")
        for c in codes:
            f.write("  {" + ",".join(f"0x{b:02X}" for b in chosen[c]) + "},\n")
        f.write("};\n")
    print(len(codes), "glyphs,", len(codes) * 15, "bytes")


main()
