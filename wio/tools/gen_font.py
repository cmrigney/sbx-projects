ALIASES = {
    0x23FA: 0x25CF,  # Claude Code's tool-call dot
    0x2714: 0x2713,
    0x2718: 0x2717,
    0x273D: 0x273B,
    0x2736: 0x273B,
    0x2733: 0x273B,
}


def parse(path):
    """Returns (width, height, {codepoint: rows}), each row left-aligned in 16 bits."""
    text = open(path, errors="ignore").read()
    w, h, _, low = map(int, re.search(r"^FONTBOUNDINGBOX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", text, re.M).groups())
    descent = -low
    mask = (0xFFFF << (16 - w)) & 0xFFFF
    glyphs = {}
    for block in re.findall(r"STARTCHAR.*?ENDCHAR", text, re.S):
        code = int(re.search(r"^ENCODING (-?\d+)", block, re.M).group(1))
        if not any(a <= code <= b for a, b in RANGES):
            continue
        _, bh, bx, by = map(int, re.search(r"^BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)", block, re.M).groups())
        rows = re.search(r"BITMAP\n(.*?)ENDCHAR", block, re.S).group(1).split()
        out = [0] * h
        top = h - descent - by - bh
        for i, row in enumerate(rows):
            y = top + i
            if 0 <= y < h:
                value = int(row, 16) << (16 - len(row) * 4)
                value = value >> bx if bx >= 0 else value << -bx
                out[y] = value & mask
        glyphs[code] = out
    return w, h, glyphs


def scaled(drawing, w, h):
    rows = drawing.strip("\n").split("\n")
    assert len(rows) == 13 and all(len(r) == 7 for r in rows)
    return [
        sum(0x8000 >> x for x in range(w) if rows[y * 13 // h][x * 7 // w] == "#")
        for y in range(h)
    ]


def main():
    output, paths = sys.argv[1], sys.argv[2:]
    tables = []
    with open(output, "w") as f:
        f.write("// X11 misc-fixed fonts (public domain). Generated by wio/tools/gen_font.py.\n")
        f.write("// Rows run top to bottom, with the leftmost pixel in the top bit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct FontData {\n  uint8_t w, h, rowBytes;\n  uint16_t count;\n")
        f.write("  const uint16_t *codes;\n  const uint8_t *bitmaps;\n};\n\n")
        for index, path in enumerate(paths):
            w, h, glyphs = parse(path)
            for code, drawing in CUSTOM.items():
                glyphs.setdefault(code, scaled(drawing, w, h))
            for code, target in ALIASES.items():
                glyphs.setdefault(code, glyphs[target])
            codes = sorted(glyphs)
            row_bytes = (w + 7) // 8
            f.write(f"static const uint16_t kCodes{index}[] = {{\n")
            for i in range(0, len(codes), 14):
                f.write("  " + ",".join(f"0x{c:04X}" for c in codes[i:i + 14]) + ",\n")
            f.write(f"}};\nstatic const uint8_t kBits{index}[] = {{\n")
            for c in codes:
                data = []
                for row in glyphs[c]:
                    data.append(row >> 8)
                    if row_bytes == 2:
                        data.append(row & 0xFF)
                f.write("  " + ",".join(f"0x{b:02X}" for b in data) + ",\n")
            f.write("};\n\n")
            tables.append(f"  {{{w}, {h}, {row_bytes}, {len(codes)}, kCodes{index}, kBits{index}}},\n")
            print(f"{w}x{h}: {len(codes)} glyphs, {len(codes) * (2 + row_bytes * h)} bytes")
        f.write("static const FontData kFonts[] = {\n" + "".join(tables) + "};\n")


main()
